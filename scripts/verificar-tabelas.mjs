// PostgreSQL local em memoria; nao usa credenciais nem acessa o Supabase.
import { PGlite } from '../.verificacao/node_modules/@electric-sql/pglite/dist/index.js';
import { readFileSync, readdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const banco = new PGlite();
try {
  // Estrutura minima das entidades preexistentes, apenas para testar as migrations.
  await banco.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create schema storage;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table cliente(id_cliente integer generated by default as identity primary key,nome text,email text,telefone text);
    create table funcionario(id_funcionario integer generated by default as identity primary key,nome text,email text,telefone text,cpf text,cargo text,perfil_acesso text,auth_user_id uuid);
    create table mecanico(id_funcionario integer primary key);
    create table moto(id_moto integer generated by default as identity primary key,id_cliente integer,modelo text,placa text,ano integer,cor text,foto text,quilometragem integer);
    create table ordem_servico(id_os integer generated by default as identity primary key,id_moto integer,id_mecanico integer,status text default 'aguardando',observacoes text,problema_relatado text,data_entrada timestamp,data_saida timestamp,previsao_entrega timestamp,quilometragem_entrada integer,quilometragem_saida integer,total numeric, constraint check_status_os check(status in ('aguardando','em andamento','pronto','entregue')));
    create table foto_os(id_foto integer generated by default as identity primary key,id_os integer,tipo text,url text,data_registro timestamp);
    create table notificacao(id_os integer);
    create table os_peca(id_os integer,nome_peca text,quantidade integer,preco_unitario numeric);
    create table os_servico(id_os integer,descricao text,preco numeric);
    create table orcamento(id_os integer);
  `);
  const arquivos = readdirSync('supabase/migrations')
    .filter((funcaoAtual) => funcaoAtual.endsWith('.sql'))
    .sort();
  const migracao = arquivos.find((funcaoAtual) => funcaoAtual.includes('simplificar_admin'));
  for (const funcaoAtual of arquivos.filter((funcaoAtual) => funcaoAtual < migracao))
    await banco.exec(readFileSync(`supabase/migrations/${funcaoAtual}`, 'utf8'));
  await banco.exec(readFileSync('supabase/inspecao.sql', 'utf8'));
  const autor = '00000000-0000-4000-8000-000000000001';
  await banco.exec(`
    insert into auth.users values('${autor}');
    insert into cliente(nome) values('Cliente teste');
    insert into moto(id_cliente,modelo,placa) values(1,'Honda CG 160','ABC1234');
    insert into ordem_servico(id_moto,observacoes) values(1,'Texto original');
    insert into order_observation_migration_backup values(1,'Backup integral','2026-09-01T12:00:00Z');
    insert into admin_notification_receipts(notification_id,admin_user_id,read_at) select id,'${autor}',now() from admin_notifications;
    select admin_order_status(1,'em andamento','Início','${autor}');
  `);
  const escalar = async (sql) => Object.values((await banco.query(sql)).rows[0])[0];
  // Relacao explicita da auditoria antiga; dois eventos identicos sem vinculo
  // nao podem ser descartados por semelhanca ou proximidade no tempo.
  await banco.exec(`
    update order_status_history set audit_id=(select id from order_admin_audit limit 1);
    insert into order_admin_audit(order_id,action,admin_user_id,occurred_at,details)
      select order_id,action,admin_user_id,occurred_at,details from order_admin_audit;
    insert into admin_notifications(kind,order_id,title,body)
      values('waiting_part',1,'Peça','Aviso antigo'),('ready',1,'Pronta','Aviso antigo'),('cancelled',1,'Cancelada','Aviso antigo');
    insert into order_status_history(order_id,previous_status,next_status,note,changed_at)
      values(999,'aguardando','pronto','Nota igual','2026-09-01T12:00:00Z'),
            (999,'aguardando','pronto','Nota igual','2026-09-01T12:00:00Z');
    insert into order_admin_audit(order_id,action,admin_user_id,details) values(999,'delete','${autor}','{"motivo":"Antiga","permanent":true}');
    insert into order_observation_history(order_id,kind,body) values(999,'previous_observation','OS já excluída');
    insert into cliente(nome) values('Outro cliente');
    insert into client_admin_audit(client_id,client_name,admin_user_id,action,reason,occurred_at)
      values(1,'Nome registrado','${autor}','archive','Motivo antigo','2026-08-01T10:00:00Z');
    insert into motorcycle_thumbnail_jobs(model_key,model,status,next_retry_at,locked_at,locked_by,last_error,attempts)
      select 'modelo '||n,'Modelo '||n,estado,now()+interval '1 year',now()+interval '1 year','${autor}','Erro preservado',3
      from unnest(array['pending','processing','waiting_quota','retry','needs_review','done']) with ordinality t(estado,n);
  `);
  const filaAntes = (
    await banco.query(`select id,model_key as chave,model as modelo,
    case status when 'pending' then 'pendente' when 'processing' then 'processando' when 'waiting_quota' then 'aguardando_cota' when 'retry' then 'tentar_novamente' when 'needs_review' then 'aguardando_revisao' when 'done' then 'concluido' end as status,
    attempts as tentativas,next_retry_at as tentar_em,locked_at as travado_em,locked_by as id_executor,last_error as erro,created_at as criado_em,updated_at as atualizado_em from motorcycle_thumbnail_jobs order by id`)
  ).rows;
  const avisoAntes = (
    await banco.query(
      `select id,case kind when 'new_order' then 'nova_os' when 'waiting_part' then 'aguardando_peca' when 'ready' then 'pronta' when 'cancelled' then 'cancelada' end as tipo,order_id as id_os,title as titulo,body as mensagem,created_at as criado_em from admin_notifications order by id`,
    )
  ).rows;
  const readingsAntes = (
    await banco.query(
      'select notification_id as id_aviso,admin_user_id as id_usuario,read_at as lido_em,dismissed_at as dispensado_em from admin_notification_receipts order by notification_id,admin_user_id',
    )
  ).rows;
  const clienteAntes = (
    await banco.query(
      `select id,client_id as id_cliente,client_name as nome,admin_user_id as id_usuario,'arquivar' as acao,reason as motivo,occurred_at as criado_em from client_admin_audit order by id`,
    )
  ).rows;
  const dominioSchema = `select table_schema,table_name,column_name,data_type,is_nullable,column_default from information_schema.columns where table_schema='public' and table_name in ('cliente','moto','ordem_servico','funcionario','mecanico','foto_os','notificacao','os_peca','os_servico','orcamento','pagamento_os') order by table_name,ordinal_position`;
  const permissoesDominio = `select grantee,table_name,privilege_type from information_schema.role_table_grants where table_schema='public' and table_name in ('cliente','moto','ordem_servico','funcionario','mecanico','foto_os','notificacao','os_peca','os_servico','orcamento','pagamento_os') order by table_name,grantee,privilege_type`;
  const dominioAntes = (await banco.query(dominioSchema)).rows;
  const grantsAntes = (await banco.query(permissoesDominio)).rows;
  const armazenamentoAntes = (await banco.query('select * from storage.buckets order by id')).rows;
  const copiaSegurancaAntes = (
    await banco.query(
      'select order_id as id_os,original_body as texto,saved_at as salvo_em from order_observation_migration_backup order by order_id',
    )
  ).rows;
  for (const funcaoAtual of arquivos.filter((funcaoAtual) => funcaoAtual >= migracao)) {
    const sql = readFileSync(`supabase/migrations/${funcaoAtual}`, 'utf8');
    if (funcaoAtual.includes('simplificar_admin')) {
      await banco.exec(
        "update order_status_history set previous_status='Incompatível' where audit_id is not null",
      );
      await assert.rejects(banco.exec(sql), /audit_id incompatível/);
      await banco.exec('rollback');
      assert.equal(
        await escalar("select to_regclass('public.admin_notifications')::text"),
        'admin_notifications',
      );
      await banco.exec(
        "update order_status_history set previous_status='aguardando' where audit_id is not null",
      );
    }
    if (funcaoAtual.includes('simplificar_admin')) {
      await banco.exec(
        'create view dependente_externo as select * from order_observation_migration_backup',
      );
      await assert.rejects(banco.exec(sql), /Dependências externas/);
      await banco.exec('rollback');
      assert.equal(
        await escalar("select to_regclass('public.order_observation_migration_backup')::text"),
        'order_observation_migration_backup',
      );
      await banco.exec('drop view dependente_externo');
    }
    await banco.exec(sql);
  }
  assert.deepEqual(
    (await banco.query('select * from recuperacao.os_backup order by id_os')).rows,
    copiaSegurancaAntes,
  );
  assert.deepEqual(
    (await banco.query('select * from miniaturas_motos order by id')).rows,
    filaAntes,
  );
  assert.deepEqual((await banco.query('select * from admin_notify order by id')).rows, avisoAntes);
  assert.deepEqual(
    (await banco.query('select * from admin_leitura order by id_aviso,id_usuario')).rows,
    readingsAntes,
  );
  assert.deepEqual(
    (await banco.query('select * from cliente_historico order by id')).rows,
    clienteAntes,
  );
  assert.deepEqual((await banco.query(dominioSchema)).rows, dominioAntes);
  assert.deepEqual((await banco.query(permissoesDominio)).rows, grantsAntes);
  assert.deepEqual(
    (await banco.query('select * from storage.buckets order by id')).rows,
    armazenamentoAntes,
  );
  assert.equal(await escalar('select texto from recuperacao.os_backup'), 'Backup integral');
  assert.equal(
    await escalar("select count(*)::int from os_historico where id_os=999 and tipo='status'"),
    2,
  );
  assert.equal(await escalar('select count(*)::int from os_historico where id_os=1'), 2);
  assert.equal(
    await escalar(
      "select count(*)::int from os_historico where id_os=1 and tipo='auditoria_status'",
    ),
    1,
  );
  assert.equal(
    await escalar(
      "select (dados->'auditoria'->>'id')::int from os_historico where id_os=1 and tipo='status'",
    ),
    1,
  );
  assert.equal(await escalar('select count(*)::int from os_historico where id_usuario is null'), 3);
  assert.equal(
    await escalar("select count(*)::int from os_historico where texto='Backup integral'"),
    0,
  );
  await banco.exec(`update ordem_servico set observacoes='Texto editado' where id_os=1;`);
  await assert.rejects(
    banco.exec(`select alterar_status_os(1,'cancelada','','${autor}')`),
    /motivo/i,
  );
  await banco.exec(`select alterar_status_os(1,'cancelada','Cliente desistiu','${autor}');`);
  assert.equal(
    await escalar("select count(*)::int from os_historico where id_os=1 and tipo='status'"),
    2,
  );
  await banco.exec(`select arquivar_cliente(1,'${autor}','Cadastro duplicado');`);
  assert.equal(await escalar('select acao from cliente_historico'), 'arquivar');
  assert.equal(await escalar('select count(*)::int from moto where id_cliente=1'), 1);
  assert.equal(await escalar('select count(*)::int from ordem_servico where id_os=1'), 1);
  await banco.exec(
    `select editar_os(1,'Cliente editado','','','', 'Honda CG 160','ABC1234',2025,'','Problema','Observação final','${autor}');`,
  );
  assert.equal(await escalar('select nome from cliente where id_cliente=2'), 'Outro cliente');
  // Mecanico: o gatilho conserva auth.uid(), sem atribuir um administrador ficticio.
  const mecanico = '00000000-0000-4000-8000-000000000002';
  await banco.exec(
    `select set_config('request.jwt.claim.sub','${mecanico}',false); update ordem_servico set status='pronto' where id_os=1;`,
  );
  assert.equal(
    await escalar(
      "select id_usuario::text from os_historico where tipo='status' and novo='pronto' and id_os=1",
    ),
    mecanico,
  );
  // Contrato existente do cancelamento por recusa de orcamento, fora do admin.
  await banco.exec(
    "begin; select set_config('app.order_note','Orçamento recusado pelo cliente via WhatsApp.',true); update ordem_servico set status='cancelada' where id_os=1; commit;",
  );
  assert.equal(
    await escalar(
      "select texto from os_historico where tipo='status' and novo='cancelada' order by id desc limit 1",
    ),
    'Orçamento recusado pelo cliente via WhatsApp.',
  );
  const segundo = '00000000-0000-4000-8000-000000000003';
  await banco.exec(`insert into auth.users values('${segundo}');`);
  assert.equal(
    await escalar(`select count(*)::int from admin_leitura where id_usuario='${segundo}'`),
    0,
  );
  await banco.exec(
    `insert into admin_leitura(id_aviso,id_usuario,lido_em) select id,'${segundo}',now() from admin_notify limit 1;`,
  );
  assert.equal(
    await escalar(`select count(*)::int from admin_leitura where id_usuario='${autor}'`),
    1,
  );
  // Fila: reserva unica, retomada e token que rejeita conclusao pelo executor antigo.
  await banco.exec(`select * from reservar_miniatura('${autor}');`);
  assert.equal(await escalar(`select count(*)::int from reservar_miniatura('${segundo}')`), 0);
  assert.equal(
    await escalar(`select finalizar_miniatura(1,'${segundo}','concluido',now(),null)`),
    false,
  );
  await banco.exec(
    `update miniaturas_motos set travado_em=now()-interval '6 minutes' where id=1; select * from reservar_miniatura('${segundo}');`,
  );
  assert.equal(
    await escalar(`select finalizar_miniatura(1,'${autor}','concluido',now(),null)`),
    false,
  );
  assert.equal(
    await escalar(
      `select finalizar_miniatura(1,'${segundo}','aguardando_cota',now()-interval '1 second','Cota')`,
    ),
    true,
  );
  await banco.exec(
    `select * from reservar_miniatura('${autor}'); select finalizar_miniatura(1,'${autor}','tentar_novamente',now()-interval '1 second','Falha'); select * from reservar_miniatura('${autor}'); select finalizar_miniatura(1,'${autor}','aguardando_revisao',now(),null);`,
  );
  assert.equal(
    await escalar('select status from miniaturas_motos where id=1'),
    'aguardando_revisao',
  );
  assert.equal(await escalar(`select count(*)::int from reservar_miniatura('${autor}')`), 0);
  await banco.exec(
    "update miniaturas_motos set status='concluido' where id=1; select revisar_miniaturas();",
  );
  assert.equal(await escalar('select status from miniaturas_motos where id=1'), 'pendente');
  await banco.exec(
    `insert into pagamento_os(id_os,status,pago_em,valor) values(1,'pago',now(),100);`,
  );
  assert.equal(await escalar('select status from pagamento_os'), 'pago');
  const criado = await escalar(
    `select admin_create_order('{"clientName":"Novo cliente","model":"Honda Biz 125","plate":"XYZ9876","entryAt":"2026-10-30T12:00:00"}'::jsonb)->>'id'`,
  );
  assert.equal(
    await escalar(
      `select count(*)::int from admin_notify where id_os=${Number(criado)} and tipo='nova_os'`,
    ),
    1,
  );
  assert.equal(
    await escalar("select count(*)::int from miniaturas_motos where chave='honda biz 125'"),
    1,
  );
  await banco.exec(`select excluir_os(${Number(criado)},'${autor}','Teste de criação');`);
  await banco.exec(`select excluir_os(1,'${autor}','Exclusão de teste');`);
  assert.equal(
    await escalar("select dados->>'motivo' from os_historico where id_os=1 and tipo='exclusao'"),
    'Exclusão de teste',
  );
  assert.equal(await escalar('select count(*)::int from os_historico where id_os=999'), 4);
  assert.equal(await escalar('select count(*)::int from admin_leitura'), 0);
  assert.equal(await escalar('select count(*)::int from admin_notify'), 0);
  const tabelas = [
    'admin_notify',
    'admin_leitura',
    'cliente_historico',
    'miniaturas_motos',
    'os_historico',
    'pagamento_os',
  ];
  for (const tabela of tabelas) {
    assert.equal(
      await escalar(`select relrowsecurity from pg_class where oid='public.${tabela}'::regclass`),
      true,
    );
    assert.equal(
      await escalar(`select has_table_privilege('anon','public.${tabela}','select')`),
      false,
    );
    assert.equal(
      await escalar(`select has_table_privilege('authenticated','public.${tabela}','select')`),
      false,
    );
  }
  for (const cargo of ['anon', 'authenticated', 'service_role'])
    assert.equal(
      await escalar(`select has_schema_privilege('${cargo}','recuperacao','usage')`),
      false,
    );
  for (const anterior of ['os_status', 'os_observacao', 'os_auditoria'])
    assert.equal(await escalar(`select to_regclass('public.${anterior}')::text`), null);
  for (const cargo of ['anon', 'authenticated'])
    assert.equal(
      await escalar(
        `select has_function_privilege('${cargo}','public.excluir_os(integer,uuid,text)','execute')`,
      ),
      false,
    );
  assert.equal(
    await escalar(
      "select has_function_privilege('service_role','public.excluir_os(integer,uuid,text)','execute')",
    ),
    true,
  );
  assert.equal(
    await escalar(
      `select count(*)::int from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname in ('public','app_private') and p.prosrc ~ '\\m(admin_notifications|admin_notification_receipts|client_admin_audit|motorcycle_thumbnail_jobs|order_admin_audit|order_status_history|order_observation_history)\\M'`,
    ),
    0,
  );
  console.log(
    'OK: 25 migrations; unificação, vínculo explícito, eventos iguais preservados, backup privado, autor mecânico, cancelamento, edição, exclusão, arquivamento, leituras individuais, fila/retentativa/cota/revisão/token, pagamento, RLS e grants.',
  );
} catch (erro) {
  console.error(
    'FALHOU:',
    erro.message,
    'código:',
    erro.code ?? '',
    erro.detail ?? '',
    erro.where ?? '',
  );
  process.exitCode = 1;
} finally {
  await banco.close();
}
